-- Paso 3: presupuestos por evento y por persona (docs/SPEC-limites-por-persona.md).
-- La asignación (presupuesto + persona + monto, categoría opcional) es la aprobación humana por adelantado;
-- dentro de ella el código paga solo. La tabla event queda como política general: nombre, tope por ticket
-- y presupuesto total (saldo de la wallet del agente). Las fechas pasan a cada presupuesto y las categorías
-- a su propia tabla.

CREATE TABLE categories (
  key TEXT PRIMARY KEY CHECK (key ~ '^[a-z_]{2,30}$' AND key NOT IN ('otra', 'indeterminada')),
  name TEXT NOT NULL,
  -- La usa el agente para clasificar: qué entra y qué no en esta categoría.
  description TEXT NOT NULL DEFAULT '',
  active BOOLEAN NOT NULL DEFAULT true,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
ALTER TABLE categories ENABLE ROW LEVEL SECURITY;

CREATE TABLE budgets (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  starts_on TEXT NOT NULL,
  ends_on TEXT NOT NULL,
  -- Máximo por ticket para el pago automático. 0 = sin pago automático (todo lo aprueba el owner).
  autopay_max_per_receipt_cents BIGINT NOT NULL DEFAULT 0 CHECK (autopay_max_per_receipt_cents >= 0),
  status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'closed')),
  created_by INTEGER REFERENCES members(id),
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  CHECK (starts_on <= ends_on)
);
ALTER TABLE budgets ENABLE ROW LEVEL SECURITY;

CREATE TABLE assignments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  budget_id INTEGER NOT NULL REFERENCES budgets(id),
  member_id INTEGER NOT NULL REFERENCES members(id),
  -- NULL = cualquier categoría permitida.
  category_key TEXT REFERENCES categories(key),
  amount_cents BIGINT NOT NULL CHECK (amount_cents >= 0),
  created_by INTEGER REFERENCES members(id),
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  -- Una sola asignación por persona, presupuesto y categoría (y una sola "sin categoría").
  UNIQUE NULLS NOT DISTINCT (budget_id, member_id, category_key)
);
ALTER TABLE assignments ENABLE ROW LEVEL SECURITY;

ALTER TABLE requests ADD COLUMN budget_id INTEGER REFERENCES budgets(id);
ALTER TABLE requests ADD COLUMN assignment_id INTEGER REFERENCES assignments(id);
CREATE INDEX requests_budget ON requests (budget_id);

-- amount_cents de la autorización es lo aprobado (lo que se paga). requested_cents, el importe del ticket.
ALTER TABLE authorizations ADD COLUMN assignment_id INTEGER REFERENCES assignments(id);
ALTER TABLE authorizations ADD COLUMN requested_cents BIGINT;
ALTER TABLE authorizations ADD COLUMN exception_cents BIGINT NOT NULL DEFAULT 0 CHECK (exception_cents >= 0);
ALTER TABLE authorizations ADD COLUMN exception_reason TEXT;
ALTER TABLE authorizations ADD COLUMN mode TEXT NOT NULL DEFAULT 'full' CHECK (mode IN ('auto', 'full', 'up_to_balance', 'exception'));
UPDATE authorizations
  SET requested_cents = amount_cents,
      mode = CASE WHEN authorized_by LIKE 'agente · pago automático%' THEN 'auto' ELSE 'full' END;
CREATE INDEX authorizations_assignment ON authorizations (assignment_id) WHERE revoked_at IS NULL;

-- Datos existentes: las categorías y el evento de la demo pasan a la tabla nueva y a un primer presupuesto.
INSERT INTO categories (key, name, description, created_at, updated_at)
SELECT c, initcap(c),
       CASE c
         WHEN 'transporte' THEN 'Remises, taxis, colectivos y viajes para el evento.'
         WHEN 'materiales' THEN 'Insumos para el evento: librería, impresiones, ferretería, señalética.'
         ELSE ''
       END,
       e.created_at, e.created_at
FROM event e, jsonb_array_elements_text(e.categories::jsonb) AS c
WHERE c ~ '^[a-z_]{2,30}$' AND c NOT IN ('otra', 'indeterminada')
ON CONFLICT (key) DO NOTHING;

INSERT INTO budgets (name, starts_on, ends_on, autopay_max_per_receipt_cents, created_at, updated_at)
SELECT e.name, e.start_date, e.end_date,
       COALESCE((SELECT s.auto_pay_limit_cents FROM agent_settings s WHERE s.id = 1), 10000),
       e.created_at, e.created_at
FROM event e;
UPDATE requests SET budget_id = (SELECT min(id) FROM budgets) WHERE budget_id IS NULL;

ALTER TABLE event DROP COLUMN start_date;
ALTER TABLE event DROP COLUMN end_date;
ALTER TABLE event DROP COLUMN categories;

