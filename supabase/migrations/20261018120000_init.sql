-- Esquema inicial de Respend en Postgres (paridad con la versión SQLite).
-- Dinero en enteros: centavos en BIGINT, montos en wei como TEXT (decimal). Fechas como texto ISO 8601,
-- igual que en SQLite: se comparan como strings y la UI no cambia.
-- Las tablas tienen RLS activado y ninguna política: solo el servidor (rol postgres) las lee y escribe.

CREATE TABLE event (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  name TEXT NOT NULL,
  start_date TEXT NOT NULL,
  end_date TEXT NOT NULL,
  categories TEXT NOT NULL,
  cap_per_receipt_cents BIGINT NOT NULL,
  budget_cents BIGINT NOT NULL,
  policy_version INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

CREATE TABLE requests (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  description TEXT NOT NULL,
  recipient TEXT NOT NULL,
  file_path TEXT NOT NULL,
  file_sha256 TEXT NOT NULL,
  mime TEXT NOT NULL,
  status TEXT NOT NULL,
  ai_output TEXT,
  ai_model TEXT,
  ai_provider TEXT,
  ai_ran_at TEXT,
  ai_error TEXT,
  ai_fake INTEGER NOT NULL DEFAULT 0,
  claimant_name TEXT,
  receipt_date TEXT,
  merchant TEXT,
  concept TEXT,
  amount_cents BIGINT,
  currency TEXT,
  category TEXT,
  fields_source TEXT,
  checks TEXT,
  duplicate_flags TEXT,
  recommendation TEXT,
  explanation TEXT,
  policy_version INTEGER
);
CREATE INDEX requests_file_sha256 ON requests (file_sha256);
CREATE INDEX requests_date_amount ON requests (receipt_date, amount_cents);

CREATE TABLE clarifications (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id INTEGER NOT NULL REFERENCES requests(id),
  author TEXT NOT NULL CHECK (author IN ('agent','collaborator','organizer')),
  message TEXT NOT NULL,
  created_at TEXT NOT NULL
);
CREATE INDEX clarifications_request ON clarifications (request_id);

CREATE TABLE authorizations (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id INTEGER NOT NULL REFERENCES requests(id),
  amount_cents BIGINT NOT NULL,
  token_amount TEXT NOT NULL,
  token_address TEXT NOT NULL,
  chain_id INTEGER NOT NULL,
  recipient TEXT NOT NULL,
  binding_hash TEXT NOT NULL,
  policy_version INTEGER NOT NULL,
  authorized_by TEXT NOT NULL,
  review_note TEXT,
  created_at TEXT NOT NULL,
  revoked_at TEXT,
  revoke_reason TEXT
);
-- Una sola autorización vigente por solicitud.
CREATE UNIQUE INDEX one_active_authorization_per_request
  ON authorizations (request_id) WHERE revoked_at IS NULL;

CREATE TABLE payments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id INTEGER NOT NULL REFERENCES requests(id),
  authorization_id INTEGER NOT NULL REFERENCES authorizations(id),
  mode TEXT NOT NULL CHECK (mode IN ('simulated','mainnet')),
  status TEXT NOT NULL CHECK (status IN ('preparing','signed','sent','confirmed','failed','uncertain')),
  from_address TEXT,
  nonce BIGINT,
  raw_tx TEXT,
  tx_hash TEXT,
  block_number BIGINT,
  attribution_ok INTEGER,
  error TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
-- Una solicitud no se paga dos veces: a lo sumo un pago no fallido por solicitud.
CREATE UNIQUE INDEX one_live_payment_per_request
  ON payments (request_id) WHERE status <> 'failed';
-- Bloqueo global de pagos como segunda barrera (la primera es el chequeo en payTool, dentro del lock
-- de escritura): a lo sumo un pago en curso en toda la base, así nunca hay dos nonces en vuelo.
CREATE UNIQUE INDEX one_payment_in_flight
  ON payments ((true)) WHERE status IN ('preparing','signed','sent','uncertain');

CREATE TABLE audit_log (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id INTEGER,
  actor TEXT NOT NULL,
  action TEXT NOT NULL,
  detail TEXT,
  created_at TEXT NOT NULL
);
CREATE INDEX audit_log_request ON audit_log (request_id);

-- Wallet de cobro del colaborador (piloto: un solo colaborador). La define el propio colaborador.
CREATE TABLE collaborator_profile (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  wallet TEXT NOT NULL,
  name TEXT,
  updated_at TEXT NOT NULL
);

-- Configuración del agente que define el organizador.
-- auto_pay_limit_cents: hasta ese monto (inclusive) el agente paga solo los gastos sin alertas. 0 = apagado.
-- auto_pay_daily_cap_cents: tope de 24 h. NULL = automático (3 veces el límite por gasto).
CREATE TABLE agent_settings (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  auto_pay_limit_cents BIGINT NOT NULL CHECK (auto_pay_limit_cents >= 0),
  auto_pay_daily_cap_cents BIGINT CHECK (auto_pay_daily_cap_cents >= 0),
  updated_at TEXT NOT NULL
);

