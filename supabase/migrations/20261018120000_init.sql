ALTER TABLE audit_log ENABLE ROW LEVEL SECURITY;
ALTER TABLE collaborator_profile ENABLE ROW LEVEL SECURITY;
ALTER TABLE agent_settings ENABLE ROW LEVEL SECURITY;
