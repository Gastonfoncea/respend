-- Paso 2: personas con login. Reemplaza los códigos compartidos y el perfil único de colaborador.
-- auth_user_id es el id del usuario en Supabase Auth (o en el proveedor local de desarrollo).
-- La wallet de cobro la fija el organizador; los gastos guardan una copia al presentarse.
CREATE TABLE members (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  auth_user_id TEXT UNIQUE,
  email TEXT NOT NULL UNIQUE CHECK (email = lower(email)),
  name TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('organizer','collaborator')),
  wallet TEXT,
  active BOOLEAN NOT NULL DEFAULT true,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
ALTER TABLE members ENABLE ROW LEVEL SECURITY;

-- Quién presentó cada gasto. Los gastos de antes del login quedan sin miembro (solo los ve el organizador).
ALTER TABLE requests ADD COLUMN member_id INTEGER REFERENCES members(id);
CREATE INDEX requests_member ON requests (member_id);

-- El perfil único del piloto pasa a ser por persona (members.name y members.wallet).
DROP TABLE collaborator_profile;
